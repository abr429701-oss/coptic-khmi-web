const LanguageContext = createContext<LanguageContextProps | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
    const [language, setLanguageState] = useState<Lang>("ar");

    useEffect(() => {
        const loadLang = async () => {
            const saved = await AsyncStorage.getItem(LANG_KEY);
            if (saved && (saved === "ar" || saved === "en" || saved === "fr" || saved === "de")) {
                setLanguageState(saved as Lang);
            }
        };
        loadLang();
    }, []);

    const setLanguage = async (l: Lang) => {
        setLanguageState(l);
        await AsyncStorage.setItem(LANG_KEY, l);
        logActivity("settings_change", undefined, JSON.stringify({ language: l }));
    };

    const t = translations[language];
    const isRTL = language === "ar";

    return (
        <LanguageContext.Provider value={{
            language,
            lang: language,
            setLanguage,
            setLang: setLanguage,
            t,
            isRTL
        }}>
            {children}
        </LanguageContext.Provider>
    );
};

export const useLanguage = () => {
    const context = useContext(LanguageContext);
    if (!context) throw new Error("useLanguage must be used within LanguageProvider");
    return context;
};

export const useLang = (): LanguageContextProps => {
    return useLanguage();
};
