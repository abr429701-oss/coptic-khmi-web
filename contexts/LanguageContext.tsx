export type Lang = "ar" | "en" | "fr" | "de";

type DictionaryTermTranslations = Partial<Record<Lang, string>>;
const normalizeTermKey = (value: string) => value
    .normalize("NFC")
    .toLowerCase()
    .trim()
    .replace(/\s+/g, " ")
    .replace(/\s*،\s*/g, "،")
    .replace(/\s*,\s*/g, ",");

const dictionaryTermTranslations = new Map<string, DictionaryTermTranslations>(
    Object.entries(dictionaryTermTranslationsJson as Record<string, DictionaryTermTranslations>)
        .map(([source, translated]) => [normalizeTermKey(source), translated])
);

